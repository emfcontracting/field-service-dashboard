select i.payment_reference as check_number, min(i.paid_at) as paid,
       count(*) as invoices, sum(i.paid_amount) as paid_total
  from public.invoices i
 where i.payment_source = 'ups_corpay_report_2026-09-09'
 group by i.payment_reference
 order by paid;

-- Check 2: short pays — invoice billed for more than arrived
select w.wo_number, i.invoice_number, i.total as billed, i.paid_amount as paid,
       i.paid_amount - i.total as difference, i.payment_reference
  from public.invoices i join public.work_orders w on w.wo_id = i.wo_id
 where i.paid_amount is not null
   and abs(i.paid_amount - i.total) > 0.01
 order by (i.paid_amount - i.total);

