select p.wo_number, p.amount, p.check_number
  from _ups_pay p
 where not exists (
   select 1 from public.invoices i join public.work_orders w on w.wo_id = i.wo_id
    where w.wo_number = p.wo_number);

update public.invoices i
   set status            = 'paid',
       paid_at           = coalesce(i.paid_at, p.paid_date),
       paid_amount       = p.amount,
       payment_reference = p.check_number,
       payment_source    = 'ups_corpay_report_2026-09-09'
  from _ups_pay p
  join public.work_orders w on w.wo_number = p.wo_number
 where i.wo_id = w.wo_id
   and coalesce(i.status, '') <> 'paid';

-- Already paid: fill in the cheque detail without touching status or paid_at.
update public.invoices i
   set paid_amount       = coalesce(i.paid_amount, p.amount),
       payment_reference = coalesce(i.payment_reference, p.check_number),
       payment_source    = coalesce(i.payment_source, 'ups_corpay_report_2026-09-09')
  from _ups_pay p
  join public.work_orders w on w.wo_number = p.wo_number
 where i.wo_id = w.wo_id
   and i.status = 'paid'
   and i.payment_reference is null;

